#[test]
fn emits_a_readable_single_file_atcoder_submission() {
    let directory = NativeFixture::new("driver-atcoder");
    let source = directory.write(
        "program.mal",
        "require \"./answer.mal\";\n\
         // The answer remains readable at the top of Main.cpp.\n\
         main :: Unit -> Int32 := () -> { answer(); };\n",
    );
    directory.write(
        "answer.mal",
        "require \"./host.c\";\nextern answer :: Unit -> Int32;\n",
    );
    directory.write(
        "host.c",
        "#include \"program.mal.h\"\n\
         MAL_DEFINE_answer(call) { return 7; }\n",
    );
    let submission = directory.join("Main.cpp");
    let executable = directory.join("submission");

    let output = directory.malc([
        OsStr::new("emit"),
        OsStr::new("atcoder"),
        source.as_os_str(),
        OsStr::new("--output"),
        submission.as_os_str(),
    ]);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );

    let text = std::fs::read_to_string(&submission).unwrap();
    assert!(text.starts_with("// Generated by malc emit atcoder."));
    assert!(text.contains("// ---- mal module: program.mal ----"));
    assert!(text.contains("// main :: Unit -> Int32 := () -> { answer(); };"));
    assert!(text.contains("// ---- mal module: answer.mal ----"));
    assert!(text.contains("asm(R\"mal0("));
    assert!(!text.contains("\n\t.addrsig"));

    let compile = Command::new("clang")
        .args(["-x", "c++", "-O2"])
        .arg(&submission)
        .arg("-o")
        .arg(&executable)
        .output()
        .expect("compile generated AtCoder submission");
    assert!(
        compile.status.success(),
        "{}",
        String::from_utf8_lossy(&compile.stderr)
    );
    assert_eq!(directory.run(executable).status.code(), Some(7));
}

#[test]
fn selects_optimization_profiles_at_the_public_build_boundary() {
    let directory = NativeFixture::new("driver-optimization-profile");
    let source = directory.write(
        "program.mal",
        "apply :: ((Int32 -> Int32), Int32) -> Int32 := (function, value) -> { function(value); };\n\
         walk :: Int32 -> Int32 := (value) -> { if (value == 0i32) then { 0i32 } else { apply(walk, value - 1i32) }; };\n\
         main :: Unit -> Int32 := () -> { left := \"a\" + \"b\"; text := left + \"c\"; (#text).i32 - 3i32 + walk((#text).i32); };",
    );
    let baseline = directory.join("baseline");
    let production = directory.join("production");
    let baseline_artifacts = directory.join("baseline-artifacts");
    let production_artifacts = directory.join("production-artifacts");

    for (profile, executable, artifacts) in [
        (Some("baseline"), &baseline, &baseline_artifacts),
        (None, &production, &production_artifacts),
    ] {
        let mut arguments = vec![
            OsStr::new("build"),
            source.as_os_str(),
            OsStr::new("--output"),
            executable.as_os_str(),
            OsStr::new("--artifact-dir"),
            artifacts.as_os_str(),
        ];
        if let Some(profile) = profile {
            arguments.extend([OsStr::new("--optimization"), OsStr::new(profile)]);
        }
        let output = directory.malc(arguments);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(directory.run(executable).status.code(), Some(0));
    }

    let baseline_module = std::fs::read_to_string(baseline_artifacts.join("program.ll")).unwrap();
    let production_module =
        std::fs::read_to_string(production_artifacts.join("program.ll")).unwrap();
    assert!(!baseline_module.contains("call void @mal_runtime_symbol_concatenate_consuming_left"));
    assert!(production_module.contains("call void @mal_runtime_symbol_concatenate_consuming_left"));
}

#[test]
fn retains_artifacts_uses_the_generated_header_and_forwards_clang_arguments() {
    let directory = NativeFixture::new("driver-retained-artifacts");
    let source = directory.write(
        "program.mal",
        "require \"./host.c\";\n\
         extern sine :: Float64 -> Float64;\n\
         main :: Unit -> Int32 := () -> { if (sine(0.0) == 0.0) then { 0 } else { 1 }; };",
    );
    directory.write(
        "program.mal.h",
        "#ifndef MAL_PROGRAM_MAL_H\n\
         #define MAL_PROGRAM_MAL_H\n\
         #error stale adjacent header must not be used\n\
         #endif\n",
    );
    directory.write(
        "host.c",
        "#include \"program.mal.h\"\n\
         #include <math.h>\n\
         static volatile double zero;\n\
         MAL_DEFINE_sine(call, value) {\n\
           return sin(value + zero);\n\
         }\n",
    );
    let executable = directory.join("program");
    let artifacts = directory.join("artifacts");

    let output = directory.malc([
        OsStr::new("build"),
        source.as_os_str(),
        OsStr::new("--output"),
        executable.as_os_str(),
        OsStr::new("--artifact-dir"),
        artifacts.as_os_str(),
        OsStr::new("--clang-arg"),
        OsStr::new("-fno-builtin-sin"),
        OsStr::new("--clang-arg"),
        OsStr::new("-lm"),
    ]);

    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert_eq!(directory.run(executable).status.code(), Some(0));
    assert!(
        std::fs::read_to_string(artifacts.join("program.ll"))
            .unwrap()
            .contains("target triple")
    );
    assert!(
        std::fs::read_to_string(artifacts.join("program-shim.c"))
            .unwrap()
            .contains("mal_bridge_external_0")
    );
    assert!(
        std::fs::read_to_string(artifacts.join("program.mal.h"))
            .unwrap()
            .contains("MAL_DEFINE_sine")
    );
    for runtime in ["mal.h", "runtime.h", "core.c", "control.c"] {
        assert!(artifacts.join(runtime).is_file(), "missing {runtime}");
    }
    for runtime in BYTE_RUNTIME {
        assert!(
            !artifacts.join(runtime).exists(),
            "unused runtime input {runtime}"
        );
    }
}
